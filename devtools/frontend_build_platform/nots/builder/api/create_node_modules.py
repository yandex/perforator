from dataclasses import dataclass
import json
import os
import shutil
import time

from build.plugins.lib.nots.package_manager import (
    PackageManager,
    PackageJson,
    bundle_node_modules,
    utils as pm_utils,
)
from devtools.frontend_build_platform.libraries.logging import get_logger, timeit
from .models import BaseOptions
from .utils import copy_if_not_exists, extract_peer_tars

logger = get_logger(__name__)


@dataclass(frozen=True)
class NodeModulesBuildContext:
    peer_paths: tuple[str, ...]


def _remove_volatile_json_field(path: str, field: str) -> None:
    if not os.path.exists(path):
        return

    with open(path) as f:
        data = json.load(f)

    if field not in data:
        return

    del data[field]
    with open(path, 'w') as f:
        json.dump(data, f, sort_keys=True, separators=(',', ':'))
        f.write('\n')


def _remove_volatile_yaml_field(path: str, field: str) -> None:
    if not os.path.exists(path):
        return

    try:
        import ymakeyaml as yaml
    except ImportError:
        import yaml

    with open(path) as f:
        data = yaml.load(f, Loader=yaml.CSafeLoader) or {}

    if field not in data:
        return

    del data[field]
    with open(path, 'w') as f:
        yaml.dump(data, f, Dumper=yaml.CSafeDumper)


@timeit
def bundle_node_modules_layer(node_modules_path: str, layer_path: str) -> None:
    """Create the internal, compressed node_modules cache layer."""
    import library.python.archive as archive

    _remove_volatile_yaml_field(os.path.join(node_modules_path, '.modules.yaml'), 'prunedAt')
    _remove_volatile_json_field(
        os.path.join(node_modules_path, '.pnpm-workspace-state-v1.json'),
        'lastValidatedTimestamp',
    )
    archive.tar(
        {(node_modules_path, '.')},
        layer_path,
        compression_filter=archive.ZSTD,
        compression_level=archive.Compression.Fast,
        fixed_mtime=0,
    )


@timeit
def restore_node_modules_layer_to(
    build_root: str,
    node_modules_path: str,
    layer_path: str,
) -> None:
    """Restore a cached node_modules layer, using tmpfs only for the new flow."""
    import library.python.archive as archive

    extraction_path = node_modules_path
    ram_disk_path = os.environ.get('DISTBUILD_RAM_DISK_PATH')

    if ram_disk_path:
        relative_path = os.path.relpath(node_modules_path, build_root)
        if relative_path == os.pardir or relative_path.startswith(os.pardir + os.sep):
            raise ValueError('node_modules path must be inside the build root: {}'.format(node_modules_path))
        extraction_path = os.path.join(ram_disk_path, relative_path)

    for path in {node_modules_path, extraction_path}:
        if not os.path.lexists(path):
            continue
        if os.path.islink(path) or not os.path.isdir(path):
            os.unlink(path)
        else:
            shutil.rmtree(path)

    started_at = time.monotonic()
    os.makedirs(extraction_path, exist_ok=True)
    archive.extract_tar(layer_path, extraction_path, fail_on_duplicates=False)
    logger.debug('Restored node_modules layer in %.3f s', time.monotonic() - started_at)

    if extraction_path != node_modules_path:
        os.makedirs(os.path.dirname(node_modules_path), exist_ok=True)
        os.symlink(extraction_path, node_modules_path)


def restore_node_modules_layer(args: BaseOptions) -> None:
    restore_node_modules_layer_to(
        args.arcadia_build_root,
        pm_utils.build_nm_path(args.bindir),
        args.node_modules_layer,
    )


@timeit
def create_node_modules(args: BaseOptions, original_lf_path=None):
    """Create node_modules directory in the $BINDIR"""
    # copy package.json from $S to $B
    copy_if_not_exists(pm_utils.build_pj_path(args.curdir), pm_utils.build_pj_path(args.bindir))

    pj = PackageJson.load(pm_utils.build_pj_path(args.bindir))

    if not pj.has_dependencies():
        return None

    # peers
    extract_peer_tars(args.bindir, build_root=args.arcadia_build_root)

    pm = PackageManager(
        build_root=args.arcadia_build_root,
        build_path=args.bindir,
        sources_path=args.curdir,
        nodejs_bin_path=args.nodejs_bin,
        script_path=args.pm_script,
        inject_peers=args.inject_peers,
        verbose=args.verbose,
        ld_library_path=args.ld_library_path,
    )

    workspace = pm.create_node_modules(
        yatool_prebuilder_path=args.yatool_prebuilder_path,
        use_legacy_pnpm_virtual_store=args.use_legacy_pnpm_virtual_store,
        local_cli=args.local_cli,
        original_lf_path=original_lf_path,
    )

    return NodeModulesBuildContext(
        peer_paths=tuple(workspace.get_paths(base_path=pm.module_path, ignore_self=True)),
    )


@timeit
def bundle_workspace_node_modules(args: BaseOptions, context: NodeModulesBuildContext | None):
    if not args.nm_bundle or context is None:
        return

    # Production-only pruning will be inserted immediately before this archive step.
    bundle_node_modules(
        build_root=args.arcadia_build_root,
        node_modules_path=pm_utils.build_nm_path(args.bindir),
        peers=context.peer_paths,
        bundle_path=pm_utils.build_nm_bundle_path(args.bindir),
        inject_peers=args.inject_peers,
    )


@timeit
def prepare_node_modules_layer(args: BaseOptions) -> None:
    """Materialize injected node_modules and store it as an internal cache layer."""
    create_node_modules(args)
    node_modules_path = pm_utils.build_nm_path(args.bindir)
    os.makedirs(node_modules_path, exist_ok=True)
    bundle_node_modules_layer(node_modules_path, args.node_modules_layer)
