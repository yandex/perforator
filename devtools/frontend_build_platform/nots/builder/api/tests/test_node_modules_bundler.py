import importlib
import os
import tarfile

import pytest

import library.python.archive as archive

node_modules_bundler = importlib.import_module("devtools.frontend_build_platform.nots.builder.api.node_modules_bundler")


def test_bundle_injected_node_modules_without_workspace_state(monkeypatch, tmp_path):
    node_modules_path = tmp_path / "node_modules"
    bundle_path = tmp_path / "workspace_node_modules.tar"
    archive_calls = []

    node_modules_path.mkdir()
    (node_modules_path / "package").mkdir()
    modules_yaml_path = node_modules_path / ".modules.yaml"
    modules_yaml_path.write_text("prunedAt: 12345\nstoreDir: /build/.nots/pnpm_store/v10\nhoistPattern:\n  - '*'\n")
    monkeypatch.setattr(archive, "tar", lambda *args, **kwargs: archive_calls.append((args, kwargs)))

    node_modules_bundler.bundle_node_modules(
        build_root=str(tmp_path),
        peers=[],
        node_modules_path=str(node_modules_path),
        bundle_path=str(bundle_path),
    )

    assert archive_calls
    assert modules_yaml_path.exists()
    modules_yaml = modules_yaml_path.read_text()
    assert "prunedAt" not in modules_yaml
    assert "storeDir" not in modules_yaml
    assert "hoistPattern" in modules_yaml


@pytest.mark.parametrize("prefix", ["", "devtools/service", "app/service"])
def test_prefixed_workspace_bundle(tmp_path, prefix):
    build_root = tmp_path / "build"
    node_modules = build_root / "module" / "node_modules"
    package = node_modules / "example"
    package.mkdir(parents=True)
    (package / "index.js").write_text("module.exports = 42")
    (package / "link.js").symlink_to("index.js")
    os.link(package / "index.js", package / "hard.js")
    peer = build_root / "peer" / "node_modules"
    peer.mkdir(parents=True)
    (peer / "dependency.js").write_text("peer dependency")
    bundle = tmp_path / "workspace_node_modules.tar"
    node_modules_bundler.bundle_node_modules(
        str(build_root),
        ["peer"],
        str(node_modules),
        str(bundle),
        output_prefix=prefix,
    )
    base = "/".join(filter(None, [prefix, "node_modules"]))
    with tarfile.open(bundle) as archive_file:
        names = [name.removeprefix("./") for name in archive_file.getnames()]
        assert "/".join(filter(None, [base, "example/index.js"])) in names
        if prefix:
            assert all(name == prefix or name.startswith(prefix + "/") for name in names)
        extracted = tmp_path / "restored" / "module" / "node_modules"
        node_modules_bundler.extract_node_modules(
            str(tmp_path / "restored"), str(extracted), str(bundle), output_prefix=prefix
        )
        assert not any(".peers" in name for name in names)
    assert (extracted / "example" / "index.js").read_text() == "module.exports = 42"
    assert (extracted / "example" / "hard.js").read_text() == "module.exports = 42"
    assert os.readlink(extracted / "example" / "link.js") == "index.js"
    assert (extracted / "example" / "link.js").read_text() == "module.exports = 42"


@pytest.mark.parametrize("prefix", ["", "app/service"])
@pytest.mark.parametrize("nested", [False, True])
@pytest.mark.parametrize("link_kind", ["old-relative-tmpfs", "old-absolute-tmpfs", "absolute-local", "relative-local"])
def test_export_normalizes_bin_links_and_survives_relocation(tmp_path, prefix, nested, link_kind):
    import shutil

    node_modules = tmp_path / "ram" / "slot" / "project" / "node_modules"
    package_path = ".pnpm/@scope+tool@1.0.0/node_modules/@scope/tool/dist/cli.js"
    tool = node_modules / package_path
    tool.parent.mkdir(parents=True)
    tool.write_text("portable entrypoint")
    bins = node_modules / (".pnpm/parent@1.0.0/node_modules/.bin" if nested else ".bin")
    bins.mkdir(parents=True)
    old_target = "/storage/previous-worker/tmpfs/slot/project/node_modules/" + package_path
    if link_kind == "old-relative-tmpfs":
        link = "../" * 16 + old_target.lstrip("/")
    elif link_kind == "old-absolute-tmpfs":
        link = old_target
    elif link_kind == "absolute-local":
        link = str(tool)
    else:
        link = os.path.relpath(tool, bins)
    executable = bins / "tool"
    executable.symlink_to(link)
    (bins / "regular-shim").write_text("keep shim")
    bundle = tmp_path / "workspace_node_modules.tar"

    node_modules_bundler.bundle_node_modules("/build", [], str(node_modules), str(bundle), output_prefix=prefix)

    assert os.readlink(executable) == os.path.relpath(tool, bins)
    assert (bins / "regular-shim").read_text() == "keep shim"
    relocated = tmp_path / "relocated"
    with tarfile.open(bundle) as archive_file:
        archive_file.extractall(relocated, filter="data")
    relative_bin = executable.relative_to(node_modules)
    shutil.rmtree(tmp_path / "ram")
    exported_modules = relocated / prefix / "node_modules"
    exported_bin = exported_modules / relative_bin
    assert exported_bin.resolve().is_relative_to(exported_modules)
    assert exported_bin.read_text() == "portable entrypoint"


@pytest.mark.parametrize("case", ["missing", "outside", "escape", "symlink-outside", "not-bin"])
def test_export_does_not_rewrite_unverified_bin_targets(tmp_path, case):
    from devtools.frontend_build_platform.nots.builder.api.node_modules_utils import normalize_node_modules_bin_links

    node_modules = tmp_path / "node_modules"
    bins = node_modules / ("package" if case == "not-bin" else ".bin")
    bins.mkdir(parents=True)
    target = node_modules / ".pnpm" / "tool" / "cli.js"
    target.parent.mkdir(parents=True)
    outside = tmp_path / "outside.js"
    outside.write_text("outside")
    link = "/old/tmpfs/project/node_modules/.pnpm/tool/cli.js"
    if case == "outside":
        link = str(outside)
    elif case == "escape":
        link = "/old/node_modules/.pnpm/../../outside.js"
    elif case == "symlink-outside":
        target.symlink_to(outside)
    elif case == "not-bin":
        target.write_text("internal")
    executable = bins / "tool"
    executable.symlink_to(link)

    normalize_node_modules_bin_links(str(node_modules))

    assert os.readlink(executable) == link
    assert outside.read_text() == "outside"
