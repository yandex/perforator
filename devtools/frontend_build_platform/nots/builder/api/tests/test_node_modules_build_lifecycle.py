def _run_next_build(monkeypatch, build_error=None):
    events = []
    context = object()

    class _Builder:
        output_dirs = ["dist"]

        def __init__(self, **kwargs):
            pass

        def build(self):
            events.append("build")
            if build_error is not None:
                raise build_error

        def bundle(self):
            events.append("output_bundle")

    def create_node_modules(args):
        events.append("install")
        return context

    def bundle_workspace_node_modules(args, actual_context):
        assert actual_context is context
        events.append("node_modules_bundle")

    monkeypatch.setattr(build_next, "NextBuilder", _Builder)
    monkeypatch.setattr(build_next, "create_node_modules", create_node_modules)
    monkeypatch.setattr(build_next, "bundle_workspace_node_modules", bundle_workspace_node_modules)

    args = SimpleNamespace(tsconfigs=["tsconfig.json"])
    return events, args


def test_node_modules_bundle_is_created_after_successful_build(monkeypatch):
    events, args = _run_next_build(monkeypatch)

    build_next.build_next_func(args)

    assert events == ["install", "build", "node_modules_bundle", "output_bundle"]


def test_node_modules_bundle_is_not_created_after_failed_build(monkeypatch):
    error = RuntimeError("build failed")
    events, args = _run_next_build(monkeypatch, build_error=error)

    with pytest.raises(RuntimeError, match="build failed"):
        build_next.build_next_func(args)

    assert events == ["install", "build"]


@pytest.mark.parametrize("build_fails", [False, True])
def test_ts_library_bundles_only_after_successful_build(monkeypatch, build_fails):
    events = []
    context = object()
    builder = object.__new__(ts_library_builder.TsLibraryBuilder)
    builder.options = SimpleNamespace(hermetic_node_modules=False)

    monkeypatch.setattr(builder, "_prepare_bindir", lambda: events.append("prepare"))

    def build():
        events.append("build")
        if build_fails:
            raise RuntimeError("build failed")

    monkeypatch.setattr(builder, "_build", build)
    monkeypatch.setattr(
        ts_library_builder,
        "create_node_modules",
        lambda args: events.append("install") or context,
    )

    def bundle_workspace_node_modules(args, actual_context):
        assert actual_context is context
        events.append("node_modules_bundle")

    monkeypatch.setattr(
        ts_library_builder,
        "bundle_workspace_node_modules",
        bundle_workspace_node_modules,
    )

    if build_fails:
        with pytest.raises(RuntimeError, match="build failed"):
            builder.build()
        assert events == ["prepare", "install", "build"]
    else:
        builder.build()
        assert events == ["prepare", "install", "build", "node_modules_bundle"]


