def test_hermetic_ts_library_builds_and_bundles_on_ram_disk(monkeypatch, tmp_path):
    build_root = tmp_path / "build"
    source_root = tmp_path / "source"
    ram_disk = tmp_path / "ram"
    bindir = build_root / "project"
    curdir = source_root / "project"
    output_file = bindir / "output.tar"
    package_json_content = '{"source":"curdir","dependencies":{"peer":"workspace:../peer"}}'

    bindir.mkdir(parents=True)
    curdir.mkdir(parents=True)
    (curdir / "package.json").write_text(package_json_content)
    (curdir / "pnpm-lock.yaml").write_text("source-lockfile")
    os.chmod(curdir / "package.json", 0o444)
    prepared_package_json = '{"source":"build","dependencies":{"peer":"workspace:../peer"}}'
    (bindir / "package.json").write_text(prepared_package_json)
    (bindir / "pnpm-lock.yaml").write_text("prepared-lockfile")
    (bindir / "generated.txt").write_text("generated")
    (bindir / "dist").mkdir()
    (bindir / "dist" / "stale.txt").write_text("stale")
    (bindir / "node_modules").mkdir()
    (bindir / "node_modules" / "stale.txt").write_text("stale")
    (curdir / "source.txt").write_text("source")
    peer_manifest = build_root / "peer" / "package.json"
    peer_manifest.parent.mkdir()
    peer_manifest.write_text('{"name":"peer"}')

    options = SimpleNamespace(
        arcadia_root=str(source_root),
        arcadia_build_root=str(build_root),
        bindir=str(bindir),
        curdir=str(curdir),
        output_file=str(output_file),
        node_modules_layer=str(bindir / "node_modules.layer"),
        outputs=["dist"],
        exclude_globs=[],
        hermetic_node_modules=True,
        nm_bundle=True,
    )
    base_prepare_calls = []
    monkeypatch.setenv("DISTBUILD_RAM_DISK_PATH", str(ram_disk))
    ram_disk.mkdir()
    monkeypatch.setattr(
        ts_library_builder.RamDisk,
        "select_usage",
        lambda *args, **kwargs: ts_library_builder.RamDiskUsage.FULL_BUILD,
    )
    monkeypatch.setattr(
        ts_library_builder.BaseBuilder,
        "_prepare_bindir",
        lambda self: base_prepare_calls.append(self.options.bindir),
    )

    builder = ts_library_builder.TsLibraryBuilder(options)
    ram_bindir = ram_disk / "project"

    def restore_node_modules_layer(actual_options):
        ram_node_modules = ram_bindir / "node_modules"
        ram_node_modules.mkdir(parents=True)
        stale_node_modules = bindir / "node_modules"
        for path in stale_node_modules.iterdir():
            path.unlink()
        stale_node_modules.rmdir()
        os.symlink(ram_node_modules, stale_node_modules)

    monkeypatch.setattr(ts_library_builder, "restore_node_modules_layer", restore_node_modules_layer)
    assert builder._restore_node_modules_to_ram_disk()

    (ram_disk / "unrelated").mkdir(parents=True)
    (ram_disk / "unrelated" / "temporary").write_text("temporary")

    builder._prepare_bindir()

    assert options.bindir == str(bindir)
    assert options.output_file == str(output_file)
    assert builder.options.bindir == str(ram_bindir)
    assert builder.options.output_file == str(ram_bindir / "output.tar")
    assert builder._ram_disk_usage == ts_library_builder.RamDiskUsage.FULL_BUILD
    assert builder._original_bindir == str(bindir)
    assert builder._original_output_file == str(output_file)
    assert (ram_bindir / "package.json").read_text() == prepared_package_json
    assert (ram_bindir / "pnpm-lock.yaml").read_text() == "prepared-lockfile"
    assert (ram_disk / "peer" / "package.json").read_text() == '{"name":"peer"}'
    assert os.stat(ram_bindir / "package.json").st_mode & stat.S_IWUSR
    assert (ram_bindir / "generated.txt").read_text() == "generated"
    assert (ram_bindir / "source.txt").read_text() == "source"
    assert not (ram_bindir / "dist").exists()
    assert (ram_bindir / "node_modules").is_dir()
    assert base_prepare_calls == []

    def bundle(_):
        (ram_bindir / "output.tar").write_bytes(b"output")
        (ram_bindir / "workspace_node_modules.tar").write_bytes(b"node_modules")

    monkeypatch.setattr(ts_library_builder.BaseBuilder, "bundle", bundle)
    builder.bundle()

    assert output_file.read_bytes() == b"output"
    assert (bindir / "package.json").read_text() == prepared_package_json
    assert (bindir / "pnpm-lock.yaml").read_text() == "prepared-lockfile"
    assert os.stat(bindir / "package.json").st_mode & stat.S_IWUSR
    assert (bindir / "workspace_node_modules.tar").read_bytes() == b"node_modules"
    builder.cleanup()
    assert ram_disk.exists()
    assert not list(ram_disk.iterdir())


def test_hermetic_ts_library_keeps_only_node_modules_on_ram_disk(monkeypatch, tmp_path):
    build_root = tmp_path / "build"
    source_root = tmp_path / "source"
    bindir = build_root / "project"
    ram_disk = tmp_path / "ram"
    bindir.mkdir(parents=True)
    ram_disk.mkdir()
    curdir = source_root / "project"
    curdir.mkdir(parents=True)
    (curdir / "package.json").write_text("{}")
    (bindir / "package.json").write_text("{}")
    os.chmod(bindir / "package.json", 0o444)

    options = SimpleNamespace(
        arcadia_root=str(source_root),
        arcadia_build_root=str(build_root),
        bindir=str(bindir),
        curdir=str(curdir),
        output_file=str(bindir / "output.tar"),
        node_modules_layer=str(bindir / "node_modules.layer"),
        outputs=["dist"],
        exclude_globs=[],
        hermetic_node_modules=True,
        nm_bundle=False,
    )
    monkeypatch.setenv("DISTBUILD_RAM_DISK_PATH", str(ram_disk))
    monkeypatch.setattr(
        ts_library_builder.RamDisk,
        "select_usage",
        lambda *args, **kwargs: ts_library_builder.RamDiskUsage.NODE_MODULES,
    )

    builder = ts_library_builder.TsLibraryBuilder(options)

    events = []
    monkeypatch.setattr(builder, "_prepare_bindir", lambda: events.append("prepare"))
    monkeypatch.setattr(builder, "_build", lambda: events.append("build"))

    def restore_node_modules_layer(actual_options):
        assert actual_options.bindir == str(bindir)
        assert actual_options.use_ram_disk is True
        ram_node_modules = ram_disk / "project" / "node_modules"
        ram_node_modules.mkdir(parents=True)
        (ram_disk / "temporary").write_text("temporary")
        os.symlink(ram_node_modules, bindir / "node_modules")
        events.append("restore-node-modules")

    monkeypatch.setattr(
        ts_library_builder,
        "restore_node_modules_layer",
        restore_node_modules_layer,
    )
    monkeypatch.setattr(
        ts_library_builder,
        "bundle_workspace_node_modules",
        lambda args, context: events.append("workspace-bundle"),
    )

    builder.build()

    assert builder.options is not options
    assert builder.options.bindir == str(bindir)
    assert builder.options.use_ram_disk is True
    assert builder._ram_disk_usage == ts_library_builder.RamDiskUsage.NODE_MODULES
    assert builder._original_bindir is None
    assert builder._original_output_file is None

    builder.cleanup()

    assert events == [
        "restore-node-modules",
        "prepare",
        "build",
        "workspace-bundle",
    ]
    assert bindir.exists()
    assert os.path.islink(bindir / "node_modules")
    assert os.readlink(bindir / "node_modules") == str(ram_disk / "project" / "node_modules")
    assert not os.path.exists(bindir / "node_modules")
    assert ram_disk.exists()
    assert not list(ram_disk.iterdir())


