def test_pack_preserves_generated_proto_lockfile(monkeypatch, tmp_path, auto_proto, lockfile_in_pack):
    package_json = {
        "name": "proto",
        "version": "0.0.0",
        "files": ["build", "pnpm-lock.yaml"],
    }
