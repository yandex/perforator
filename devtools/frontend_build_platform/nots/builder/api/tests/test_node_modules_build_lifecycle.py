@pytest.mark.parametrize("build_fails", [False, True])
def test_build_library_always_cleans_builder(monkeypatch, build_fails):
    events = []

    class _Builder:
        options = SimpleNamespace(outputs=["dist"])

        def __init__(self, options):
            pass

        def build(self):
            events.append("build")
            if build_fails:
                raise RuntimeError("build failed")

        def bundle(self):
            events.append("bundle")

        def cleanup(self):
            events.append("cleanup")

    monkeypatch.setattr(build_library, "TsLibraryBuilder", _Builder)

    if build_fails:
        with pytest.raises(RuntimeError, match="build failed"):
            build_library.build_library_func(SimpleNamespace())
        assert events == ["build", "cleanup"]
    else:
        assert build_library.build_library_func(SimpleNamespace()) == ["dist"]
        assert events == ["build", "bundle", "cleanup"]


@pytest.mark.parametrize("failure_stage", [None, "build", "bundle"])
def test_build_package_always_cleans_builder(monkeypatch, failure_stage):
    events = []

    class _Builder:
        def __init__(self, options):
            pass

        def build(self):
            events.append("build")
            if failure_stage == "build":
                raise RuntimeError("build failed")

        def bundle(self):
            events.append("bundle")
            if failure_stage == "bundle":
                raise RuntimeError("bundle failed")

        def cleanup(self):
            events.append("cleanup")

    monkeypatch.setattr(build_package, "PackageBuilder", _Builder)

    if failure_stage:
        with pytest.raises(RuntimeError, match=f"{failure_stage} failed"):
            build_package.build_package_func(SimpleNamespace())
        expected_events = ["build"]
        if failure_stage == "bundle":
            expected_events.append("bundle")
        assert events == [*expected_events, "cleanup"]
    else:
        assert build_package.build_package_func(SimpleNamespace()) == []
        assert events == ["build", "bundle", "cleanup"]
