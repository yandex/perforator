@pytest.mark.parametrize("parent_has_layer", [False, True])
def test_library_for_uses_parent_dependency_mode(monkeypatch, tmp_path, parent_has_layer):
    parent = tmp_path / "apps/app"
    parent.mkdir(parents=True)
    (parent / "package.json").write_text('{"name":"app"}')
    (parent / "pnpm-lock.yaml").write_text('{"lockfileVersion":"9.0","importers":{".":{}}}')
    if parent_has_layer:
        (parent / "node_modules.layer").write_text("layer")
    target = tmp_path / "apps/app__extra.hash"
    options = SimpleNamespace(
        hermetic_node_modules=True,
        prepared_deps_moddir="apps/app",
        arcadia_build_root=str(tmp_path),
        bindir=str(target),
    )
    monkeypatch.setattr(ts_library_builder.RamDisk, "from_env", lambda: None)
    builder = ts_library_builder.TsLibraryBuilder(options)
    events = []
    monkeypatch.setattr(builder, "_prepare_bindir", lambda: events.append("prepare"))
    monkeypatch.setattr(builder, "_build", lambda: events.append("build"))
    monkeypatch.setattr(ts_library_builder, "restore_node_modules_layer", lambda _: events.append("restore"))
    monkeypatch.setattr(ts_library_builder, "create_node_modules", lambda _: events.append("install"))
    monkeypatch.setattr(ts_library_builder, "bundle_workspace_node_modules", lambda *_: events.append("bundle"))

    builder.build()

    assert events == ["prepare", "restore" if parent_has_layer else "install", "build", "bundle"]
    assert builder.options.hermetic_node_modules is parent_has_layer
    assert (target / "node_modules.layer").is_file() is parent_has_layer
