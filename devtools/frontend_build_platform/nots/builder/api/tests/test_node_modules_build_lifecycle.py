@pytest.mark.parametrize("return_code", [0, 1])
def test_ts_library_inline_command_temporarily_changes_build_package_json(monkeypatch, tmp_path, return_code):
    source_dir = tmp_path / "source"
    build_dir = tmp_path / "build"
    source_dir.mkdir()
    build_dir.mkdir()
    source_package_json = source_dir / "package.json"
    build_package_json = build_dir / "package.json"
    original = {"scripts": {"build": "old-command"}}
    original_bytes = b'{\r\n  "scripts": {"build": "old-command"}\r\n}\r\n'
    source_package_json.write_bytes(original_bytes)
    build_package_json.write_bytes(original_bytes)

    builder = object.__new__(ts_library_builder.TsLibraryBuilder)
    builder.options = SimpleNamespace(
        bindir=str(build_dir),
        build_script="build",
        build_command='tsc -c "tsconfig.json" && node --run build:esm',
        nodejs_bin="/node",
        verbose=False,
        command="build-library",
    )
    monkeypatch.setattr(builder, "_get_envs", lambda: {})
    calls = []

    def run_script(args, **kwargs):
        package_json = json.loads(build_package_json.read_text())
        assert package_json["scripts"]["build"] == builder.options.build_command
        calls.append((args, kwargs))
        return return_code, "", "failed"

    monkeypatch.setattr(ts_library_builder, "popen", run_script)

    if return_code:
        with pytest.raises(ts_library_builder.BuildError):
            builder._run_build_script()
    else:
        builder._run_build_script()

    assert json.loads(source_package_json.read_bytes()) == original
    assert build_package_json.read_bytes() == original_bytes
    assert calls[0][0] == ["node", "--run", "build"]


