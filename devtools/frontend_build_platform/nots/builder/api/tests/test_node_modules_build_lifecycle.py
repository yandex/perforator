def test_library_for_rebases_lockfile_peer_contexts_and_preserves_nested_specifiers(tmp_path):
    from build.plugins.lib.nots.package_manager import Lockfile

    source = tmp_path / "apps/app"
    source.mkdir(parents=True)
    (source / "package.json").write_text('{"name":"app"}')
    data = {
        "patchedDependencies": {"peer@1.0.0": {"hash": "unchanged", "path": "patches/peer.patch"}},
        "lockfileVersion": "9.0",
        "importers": {
            ".": {"dependencies": {"peer": {"specifier": "link:./lib", "version": "link:lib"}}},
            "lib": {"dependencies": {"child": {"specifier": "file:./child", "version": "file:lib/child"}}},
        },
        "packages": {"peer@file:lib": {"resolution": {"type": "directory", "directory": "lib"}}},
        "snapshots": {"peer@file:lib(child@file:lib/child)": {"dependencies": {"child": "file:lib/child"}}},
    }
