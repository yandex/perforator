import importlib
from types import SimpleNamespace

create_node_modules_module = importlib.import_module(
    "devtools.frontend_build_platform.nots.builder.api.create_node_modules"
)


class _Workspace:
    def __init__(self, paths):
        self.paths = paths
        self.calls = []

    def get_paths(self, **kwargs):
        self.calls.append(kwargs)
        return self.paths


def _args(nm_bundle):
    return SimpleNamespace(
        arcadia_build_root="/build",
        bindir="/build/project/module",
        curdir="/source/project/module",
        nodejs_bin="/node",
        pm_script="/pnpm.cjs",
        inject_peers=False,
        verbose=False,
        ld_library_path=None,
        yatool_prebuilder_path=None,
        use_legacy_pnpm_virtual_store=False,
        local_cli=False,
        nm_bundle=nm_bundle,
    )


def test_preserves_exact_peer_paths_for_post_build_bundle(monkeypatch):
    workspace = _Workspace(["project/peer", "project/deep/peer"])
    package_manager_calls = []
    bundle_calls = []

    class _PackageManager:
        module_path = "project/module"

        def __init__(self, **kwargs):
            package_manager_calls.append(kwargs)

        def create_node_modules(self, **kwargs):
            package_manager_calls.append(kwargs)
            return workspace

    monkeypatch.setattr(create_node_modules_module, "copy_if_not_exists", lambda *args: None)
    monkeypatch.setattr(
        create_node_modules_module.PackageJson,
        "load",
        lambda path: SimpleNamespace(has_dependencies=lambda: True),
    )
    monkeypatch.setattr(create_node_modules_module, "extract_peer_tars", lambda path: None)
    monkeypatch.setattr(create_node_modules_module, "PackageManager", _PackageManager)
    monkeypatch.setattr(
        create_node_modules_module,
        "bundle_node_modules",
        lambda **kwargs: bundle_calls.append(kwargs),
    )

    args = _args(nm_bundle=True)
    context = create_node_modules_module.create_node_modules(args)

    assert workspace.calls == [{"base_path": "project/module", "ignore_self": True}]
    assert bundle_calls == []
    assert context.peer_paths == ("project/peer", "project/deep/peer")

    create_node_modules_module.bundle_workspace_node_modules(args, context)

    assert bundle_calls == [
        {
            "build_root": "/build",
            "node_modules_path": "/build/project/module/node_modules",
            "peers": ("project/peer", "project/deep/peer"),
            "bundle_path": "/build/project/module/workspace_node_modules.tar",
            "inject_peers": False,
        }
    ]
    assert "nm_bundle" not in package_manager_calls[1]


def test_post_build_helper_does_not_bundle_when_nm_bundle_is_disabled(monkeypatch):
    workspace = _Workspace(["project/peer"])

    class _PackageManager:
        module_path = "project/module"

        def __init__(self, **kwargs):
            pass

        def create_node_modules(self, **kwargs):
            return workspace

    monkeypatch.setattr(create_node_modules_module, "copy_if_not_exists", lambda *args: None)
    monkeypatch.setattr(
        create_node_modules_module.PackageJson,
        "load",
        lambda path: SimpleNamespace(has_dependencies=lambda: True),
    )
    monkeypatch.setattr(create_node_modules_module, "extract_peer_tars", lambda path: None)
    monkeypatch.setattr(create_node_modules_module, "PackageManager", _PackageManager)
    monkeypatch.setattr(
        create_node_modules_module,
        "bundle_node_modules",
        lambda **kwargs: (_ for _ in ()).throw(AssertionError("unexpected bundle")),
    )

    args = _args(nm_bundle=False)
    context = create_node_modules_module.create_node_modules(args)
    create_node_modules_module.bundle_workspace_node_modules(args, context)

    assert workspace.calls == [{"base_path": "project/module", "ignore_self": True}]
