def test_removes_volatile_node_modules_layer_metadata(monkeypatch, tmp_path):
    build_root = tmp_path / "build"
    node_modules_path = tmp_path / "node_modules"
    layer_path = tmp_path / "node_modules.layer"
    project_path = build_root / "project"
    node_modules_path.mkdir()
    (node_modules_path / ".pnpm-workspace-state-v1.json").write_text(
        json.dumps(
            {
                "lastValidatedTimestamp": 123,
                "projects": {str(project_path): {"name": "project"}},
            }
        )
    )
    (node_modules_path / ".modules.yaml").write_text(f"prunedAt: 123\nstoreDir: {build_root}/.nots/pnpm_store/v10\n")
    monkeypatch.setattr(archive, "tar", lambda *args, **kwargs: None)

