def test_prepare_node_modules_layer_cleans_tmpfs_after_failure(monkeypatch, tmp_path):
    build_root = tmp_path / "build"
    bindir = build_root / "project"
    ram_disk = tmp_path / "ram"
    ram_node_modules = ram_disk / "project" / "node_modules"
    ram_layer = ram_disk / "project" / "node_modules.layer"
    bindir.mkdir(parents=True)
    monkeypatch.setenv("DISTBUILD_RAM_DISK_PATH", str(ram_disk))

    def create_node_modules(args, node_modules_path=None, store_dir=None):
        os.makedirs(store_dir, exist_ok=True)
        with open(os.path.join(store_dir, "index"), "w") as f:
            f.write("store")
        os.makedirs(node_modules_path, exist_ok=True)

    def bundle_node_modules_layer(source, destination, backend=None):
        with open(destination, "wb") as f:
            f.write(b"partial")
        raise RuntimeError("bundle failed")

    monkeypatch.setattr(create_node_modules_module, "create_node_modules", create_node_modules)
    monkeypatch.setattr(
        create_node_modules_module,
        "bundle_node_modules_layer",
        bundle_node_modules_layer,
    )

    args = SimpleNamespace(
        arcadia_build_root=str(build_root),
        bindir=str(bindir),
        node_modules_layer=str(bindir / "node_modules.layer"),
    )
    with pytest.raises(RuntimeError, match="bundle failed"):
        create_node_modules_module.prepare_node_modules_layer(args)

    assert not ram_node_modules.exists()
    assert not ram_layer.exists()
    assert ram_disk.exists()
    assert not list(ram_disk.iterdir())
