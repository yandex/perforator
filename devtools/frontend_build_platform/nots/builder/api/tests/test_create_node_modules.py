def test_prepare_node_modules_layer_in_tmpfs_and_publish_to_build_root(monkeypatch, tmp_path):
    build_root = tmp_path / "build"
    bindir = build_root / "project" / "module"
    ram_disk = tmp_path / "ram-disk"
    node_modules_path = ram_disk / "project" / "module" / "node_modules"
    layer_path = bindir / "node_modules.layer"
    install_paths = []
    bundle_calls = []

    bindir.mkdir(parents=True)
    monkeypatch.setenv("DISTBUILD_RAM_DISK_PATH", str(ram_disk))

    def create_node_modules(args, node_modules_path=None, store_dir=None):
        install_paths.append((node_modules_path, store_dir))
        os.makedirs(store_dir, exist_ok=True)
        with open(os.path.join(store_dir, "index"), "w") as f:
            f.write("store")
        os.makedirs(node_modules_path, exist_ok=True)
        with open(os.path.join(node_modules_path, "installed"), "w") as f:
            f.write("ok")

    def bundle_node_modules_layer(source, destination, backend=None):
        bundle_calls.append((source, destination))
        with open(destination, "wb") as f:
            f.write(b"layer")

    monkeypatch.setattr(create_node_modules_module, "create_node_modules", create_node_modules)
    monkeypatch.setattr(create_node_modules_module, "bundle_node_modules_layer", bundle_node_modules_layer)

    args = SimpleNamespace(
        arcadia_build_root=str(build_root),
        bindir=str(bindir),
        node_modules_layer=str(layer_path),
    )
    create_node_modules_module.prepare_node_modules_layer(args)

    assert install_paths == [(str(node_modules_path), str(ram_disk / "pnpm-ca-store"))]
    assert bundle_calls == [
        (
            str(node_modules_path),
            str(ram_disk / "project" / "module" / "node_modules.layer"),
        )
    ]
    assert layer_path.read_bytes() == b"layer"
    assert not (bindir / "node_modules").exists()
    assert ram_disk.exists()
    assert not list(ram_disk.iterdir())


