def test_create_node_modules_replaces_existing_package_json_with_writable_copy(tmp_path):
    source_dir = tmp_path / "source"
    build_dir = tmp_path / "build"
    source_dir.mkdir()
    build_dir.mkdir()
    source_package_json = source_dir / "package.json"
    build_package_json = build_dir / "package.json"
    source_package_json.write_text("{}")
    source_package_json.chmod(0o444)
    os.link(source_package_json, build_package_json)
    source_inode = source_package_json.stat().st_ino

    args = SimpleNamespace(curdir=str(source_dir), bindir=str(build_dir))

    assert create_node_modules_module.create_node_modules(args) is None
    assert build_package_json.read_text() == "{}"
    assert build_package_json.stat().st_ino != source_inode
    assert build_package_json.stat().st_mode & stat.S_IWUSR
    assert source_package_json.stat().st_ino == source_inode
    assert source_package_json.stat().st_mode & stat.S_IWUSR == 0


