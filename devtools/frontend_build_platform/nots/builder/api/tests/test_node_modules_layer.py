from types import SimpleNamespace

from devtools.frontend_build_platform.nots.builder.api import node_modules_layer


def test_selects_tar_backend_without_tools():
    backend = node_modules_layer.backend_from_options(SimpleNamespace(squashfs_tools_path=None))
    assert isinstance(backend, node_modules_layer.TarZstdBackend)


def test_selects_squashfs_backend_with_tools():
    backend = node_modules_layer.backend_from_options(SimpleNamespace(squashfs_tools_path="/tools"))
    assert isinstance(backend, node_modules_layer.SquashFSBackend)


def test_squashfs_pack_is_reproducible(monkeypatch):
    commands = []
    monkeypatch.setattr(
        node_modules_layer,
        "_run",
        lambda command: commands.append(command) or SimpleNamespace(stdout="", stderr="", returncode=0),
    )
    monkeypatch.setattr(node_modules_layer.pm_utils, "remove_node_modules_volatile_metadata", lambda path: None)

    node_modules_layer.SquashFSBackend("/tools").pack("/node_modules", "/node_modules.layer")

    assert commands == [
        [
            "/tools/mksquashfs",
            "/node_modules",
            "/node_modules.layer",
            "-processors",
            "4",
            "-comp",
            "zstd",
            "-Xcompression-level",
            "10",
            "-noappend",
            "-repro-time",
            "0",
        ]
    ]
