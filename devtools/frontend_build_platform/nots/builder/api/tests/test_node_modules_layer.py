def test_selects_tar_backend_without_tools():
    backend = node_modules_layer.backend_from_options(SimpleNamespace(squashfs_tools_path=None))
    assert isinstance(backend, node_modules_layer.TarZstdBackend)


def test_selects_squashfs_backend_with_tools():
    backend = node_modules_layer.backend_from_options(SimpleNamespace(squashfs_tools_path="/tools"))
    assert isinstance(backend, node_modules_layer.SquashFSBackend)


def test_squashfs_pack_is_reproducible(monkeypatch):
    commands = []
    monkeypatch.setattr(
        node_modules_layer,
        "_run",
        lambda command: commands.append(command) or SimpleNamespace(stdout="", stderr="", returncode=0),
    )
    monkeypatch.setattr(node_modules_layer, "remove_node_modules_volatile_metadata", lambda path: None)

    node_modules_layer.SquashFSBackend("/tools").pack("/node_modules", "/node_modules.layer")

    assert commands == [
        [
            "/tools/mksquashfs",
            "/node_modules",
            "/node_modules.layer",
            "-processors",
            "4",
            "-comp",
            "zstd",
            "-Xcompression-level",
            "10",
            "-noappend",
            "-repro-time",
            "0",
        ]
    ]


@pytest.mark.parametrize("global_virtual_store", [False, True])
@pytest.mark.parametrize("bundle_kind", ["layer", "bundle"])
def test_node_modules_layer_keeps_packages_and_bins_after_relocation(tmp_path, global_virtual_store, bundle_kind):
    pnpm_root = os.environ["NOTS_TEST_PNPM_ROOT"]
    node = os.path.join(os.environ["NOTS_TEST_NODEJS_ROOT"], "node")
    archive_path = tmp_path / "layer-tool.tgz"
    manifest = {"name": "layer-tool", "version": "1.0.0", "bin": {"layer-tool": "bin.cjs"}}
    with tarfile.open(archive_path, "w:gz") as archive:
        for name, data, mode in [
            ("package.json", json.dumps(manifest).encode(), 0o644),
            ("bin.cjs", b"#!/usr/bin/env node\nconsole.log('layer-tool');\n", 0o755),
        ]:
            entry = tarfile.TarInfo("package/" + name)
            entry.size = len(data)
            entry.mode = mode
            archive.addfile(entry, io.BytesIO(data))

    build_root = tmp_path / "prepare"
    project = build_root / "project"
    project.mkdir(parents=True)
    (project / "package.json").write_text(
        json.dumps({"name": "project", "dependencies": {"layer-tool": "file:" + str(archive_path)}})
    )
    workspace = PnpmWorkspace(str(project / "pnpm-workspace.yaml"))
    workspace.runtime_settings = pnpm_defaults()
    workspace.settings = {"enableGlobalVirtualStore": global_virtual_store}
    workspace.write()
    store = build_root / "store"
    store.mkdir()
    pm = PackageManager(
        build_root=str(build_root),
        build_path=str(project),
        sources_path=str(project),
        nodejs_bin_path=node,
        pnpm_root=pnpm_root,
    )
    pm._exec_command(
        ["install", "--lockfile-only", "--offline", "--ignore-scripts", "--store-dir", str(store)],
        cwd=str(project),
    )

    ram_modules = tmp_path / "ram" / "prepare" / "project" / "node_modules"
    ram_modules.mkdir(parents=True)
    (project / "node_modules").symlink_to(ram_modules, target_is_directory=True)
    pm._run_pnpm_install(str(store), str(project), False, str(ram_modules), portable=True)

    backend = node_modules_layer.TarZstdBackend()
    layer = tmp_path / "node_modules.layer"
    if bundle_kind == "layer":
        backend.pack(str(ram_modules), str(layer))
    else:
        node_modules_bundler.bundle_node_modules(str(build_root), [], str(ram_modules), str(layer))
    shutil.rmtree(build_root)
    shutil.rmtree(tmp_path / "ram")
    restored = tmp_path / "consume" / "node_modules"
    restored.mkdir(parents=True)
    if bundle_kind == "layer":
        backend.unpack(str(layer), str(restored))
    else:
        node_modules_bundler.extract_node_modules(str(tmp_path / "consume"), str(restored), str(layer))

    assert (restored / "layer-tool" / "package.json").is_file()
    executable = restored / ".bin" / "layer-tool"
    assert executable.is_file()
    result = yatest.common.execute([node, str(executable)])
    assert result.std_out.strip() == b"layer-tool"
