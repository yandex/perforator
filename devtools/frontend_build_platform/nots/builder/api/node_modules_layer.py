import logging
import os
import subprocess
from dataclasses import dataclass

from build.plugins.lib.nots.package_manager import utils as pm_utils

logger = logging.getLogger(__name__)


class LayerToolError(RuntimeError):
    pass


def _run(command: list[str]) -> subprocess.CompletedProcess:
    logger.info("Running node_modules layer command: %s", " ".join(command))
    result = subprocess.run(command, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    if result.returncode:
        raise LayerToolError(
            "Command failed with code {}: {}\nstdout:\n{}\nstderr:\n{}".format(
                result.returncode,
                " ".join(command),
                result.stdout,
                result.stderr,
            )
        )
    return result


class TarZstdBackend:
    def pack(self, node_modules_path: str, layer_path: str) -> None:
        import library.python.archive as archive

        pm_utils.remove_node_modules_volatile_metadata(node_modules_path)
        archive.tar(
            {(node_modules_path, '.')},
            layer_path,
            compression_filter=archive.ZSTD,
            compression_level=archive.Compression.Fast,
            fixed_mtime=0,
        )

    def unpack(self, layer_path: str, destination: str) -> None:
        import library.python.archive as archive

        archive.extract_tar(layer_path, destination, fail_on_duplicates=False)


@dataclass
class SquashFSBackend:
    tools_path: str

    def __post_init__(self):
        self.mksquashfs = os.path.join(self.tools_path, "mksquashfs")
        self.unsquashfs = os.path.join(self.tools_path, "unsquashfs")

    def pack(self, node_modules_path: str, layer_path: str) -> None:
        pm_utils.remove_node_modules_volatile_metadata(node_modules_path)
        os.makedirs(os.path.dirname(layer_path), exist_ok=True)
        _run(
            [
                self.mksquashfs,
                node_modules_path,
                layer_path,
                "-processors",
                "4",
                "-comp",
                "zstd",
                "-Xcompression-level",
                "10",
                "-noappend",
                "-repro-time",
                "0",
            ]
        )

    def unpack(self, layer_path: str, destination: str) -> None:
        os.makedirs(destination, exist_ok=True)
        _run([self.unsquashfs, "-f", "-d", destination, layer_path])


def backend_from_options(options):
    tools_path = getattr(options, "squashfs_tools_path", None)
    return SquashFSBackend(tools_path) if tools_path else TarZstdBackend()
