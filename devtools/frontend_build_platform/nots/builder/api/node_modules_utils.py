import os

PNPM_WORKSPACE_STATE_FILENAME = ".pnpm-workspace-state-v1.json"


def normalize_node_modules_bin_links(node_modules_path):
    # TODO(DEVTOOLSSUPPORT-99546): remove this export workaround after
    # https://github.com/pnpm/pnpm/issues/17889 is fixed and RAM-backed .bin
    # links are verified to survive relocation.
    node_modules_path = os.path.realpath(node_modules_path)
    root_prefix = node_modules_path + os.sep
    for directory, dirs, files in os.walk(node_modules_path):
        if os.path.basename(directory) != ".bin":
            continue
        dirs[:] = []
        with os.scandir(directory) as entries:
            for entry in entries:
                if not entry.is_symlink():
                    continue
                link = os.readlink(entry.path)
                target = os.path.normpath(os.path.join(directory, link))
                if target.startswith(root_prefix) and not os.path.isabs(link):
                    continue
                if not target.startswith(root_prefix):
                    # A cached layer may still name the previous worker's tmpfs.
                    # Only rebase pnpm virtual-store paths with a local target.
                    _, marker, suffix = link.partition("/node_modules/.pnpm/")
                    if not marker:
                        continue
                    target = os.path.normpath(os.path.join(node_modules_path, ".pnpm", suffix))
                if (
                    not target.startswith(root_prefix)
                    or not os.path.realpath(target).startswith(root_prefix)
                    or not os.path.isfile(target)
                ):
                    continue
                os.unlink(entry.path)
                os.symlink(os.path.relpath(target, directory), entry.path)


def _remove_yaml_fields(path, fields):
    if not os.path.exists(path):
        return

    with open(path) as f:
        lines = f.readlines()

    field_prefixes = tuple(prefix for field in fields for prefix in (f"{field}:", f'  "{field}":', f"  '{field}':"))
    with open(path, "w") as f:
        f.writelines(line for line in lines if not line.startswith(field_prefixes))


def remove_node_modules_volatile_metadata(node_modules_path):
    workspace_state_path = os.path.join(node_modules_path, PNPM_WORKSPACE_STATE_FILENAME)
    if os.path.exists(workspace_state_path):
        os.remove(workspace_state_path)

    _remove_yaml_fields(
        os.path.join(node_modules_path, ".modules.yaml"),
        ("prunedAt", "storeDir"),
    )
