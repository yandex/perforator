import os
import posixpath

from build.plugins.lib.nots.package_manager.timeit import timeit
from .node_modules_utils import remove_node_modules_volatile_metadata


@timeit
def bundle_node_modules(build_root, peers, node_modules_path, bundle_path, output_prefix=""):
    """
    Creates node_modules bundle.
    Bundle contains the module's injected node_modules directory.
    :param build_root: arcadia build root
    :type build_root: str
    :param peers: list of peers (arcadia root related)
    :type peers: list of str
    :param node_modules_path: node_modules path
    :type node_modules_path: str
    :param bundle_path: tarball path
    :type bundle_path: str
    """
    import library.python.archive as archive

    # FBP-1435: dynamically generated values break the content uid.
    remove_node_modules_volatile_metadata(node_modules_path)

    def prefixed(path):
        return posixpath.join(output_prefix, path) if output_prefix else path

    archive.tar(
        {(node_modules_path, prefixed("node_modules"))},
        bundle_path,
        compression_filter=None,
        compression_level=None,
        fixed_mtime=0,
    )


def extract_node_modules(build_root, node_modules_path, bundle_path, output_prefix=""):
    """Restore the module's injected node_modules from its bundle."""
    import library.python.archive as archive

    os.makedirs(os.path.dirname(node_modules_path), exist_ok=True)

    def unprefix(name):
        name = os.fsdecode(name)
        if name.rstrip('/') == output_prefix:
            return ""
        if not name.startswith(output_prefix + '/'):
            raise ValueError(f"Archive entry {name!r} is outside output prefix {output_prefix!r}")
        return name[len(output_prefix) + 1 :]

    def entry_filter(entry):
        entry.pathname = unprefix(entry.pathname)
        if entry.ishardlink():
            entry.hardlink = os.fsencode(unprefix(entry.hardlink))
        return bool(entry.pathname)

    archive.extract_tar(
        bundle_path,
        os.path.dirname(node_modules_path),
        fail_on_duplicates=False,
        entry_filter=entry_filter if output_prefix else None,
    )
    return True
