import os

import yatest.common

from build.plugins.lib.nots.package_manager import constants as pm_constants
from build.plugins.lib.nots.package_manager import extract_node_modules
from devtools.frontend_build_platform.nots.builder.api.create_node_modules import restore_node_modules_layer_to
from devtools.frontend_build_platform.nots.builder.api.node_modules_layer import SquashFSBackend
from devtools.frontend_build_platform.nots.builder.cli.commands.recipe_utils import duration_log, resolve_recipe_arg


def run_extract_node_modules_recipe(argv: list[str]) -> None:
    build_root = yatest.common.build_path()
    source_root = yatest.common.source_path()
    global_resources = yatest.common.global_resources()
    argv = [resolve_recipe_arg(arg, build_root, source_root, global_resources) for arg in argv]

    squashfs_tools_path = None
    index = 2
    while index < len(argv):
        if argv[index] != "--squashfs-tools-path" or index + 1 >= len(argv):
            raise ValueError("Unknown extract-node-modules recipe argument: {}".format(argv[index]))
        squashfs_tools_path = argv[index + 1]
        index += 2

    node_modules_path = yatest.common.build_path(os.path.join(argv[0], pm_constants.NODE_MODULES_DIRNAME))
    is_layer = os.path.basename(argv[1]) == pm_constants.NODE_MODULES_LAYER_FILENAME
    if is_layer:
        archive_path = yatest.common.build_path(os.path.join(argv[0], argv[1]))
    else:
        archive_path = yatest.common.project_path(argv[1])

    if archive_path and os.path.exists(archive_path):
        with duration_log("extract_node_modules"):
            if is_layer:
                backend = SquashFSBackend(squashfs_tools_path) if squashfs_tools_path else None
                restore_node_modules_layer_to(build_root, node_modules_path, archive_path, backend=backend)
            else:
                extract_node_modules(build_root, node_modules_path, archive_path)
