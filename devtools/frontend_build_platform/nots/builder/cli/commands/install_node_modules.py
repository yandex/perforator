import argparse

import yatest.common

from devtools.frontend_build_platform.nots.builder.api import BaseOptions, create_node_modules
from devtools.frontend_build_platform.nots.builder.cli.cli_args import parse_args, register_base_args
from devtools.frontend_build_platform.nots.builder.cli.commands.recipe_utils import duration_log, resolve_recipe_arg


class InstallNodeModulesOptions(BaseOptions):
    for_path: str | None


def run_install_node_modules_recipe(argv: list[str]) -> None:
    parser = argparse.ArgumentParser(prog="nots_builder install-node-modules recipe")
    register_base_args(parser)
    parser.add_argument("--for-path", required=False)

    build_root = yatest.common.build_path()
    source_root = yatest.common.source_path()
    global_resources = yatest.common.global_resources()
    args: InstallNodeModulesOptions = parse_args(
        parser,
        [resolve_recipe_arg(arg, build_root, source_root, global_resources) for arg in argv],
    )
    args.verbose = True

    if args.for_path:
        args.bindir = yatest.common.build_path(args.for_path)
        args.curdir = yatest.common.source_path(args.for_path)
        args.moddir = args.for_path

    with duration_log("create_node_modules"):
        create_node_modules(args)
